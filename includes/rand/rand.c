/* ******************************************************************************** */

#include "rand.h"

/* ******************************************************************************** */

i32 igetRand(i32 lo, i32 hi){
    assert(lo < hi);

    srand(time(NULL));

    return lo + rand() % (hi-lo+1);
}

/* ******************************************************************************** */

f32 fgetRand(f32 lo, f32 hi){
    assert(lo < hi);

    f32 result = igetRand(lo*1000, hi*1000);

    return result/1000;
}

